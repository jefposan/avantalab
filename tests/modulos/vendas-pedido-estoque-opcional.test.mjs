    const fiscalStatusBefore = (await loadControlled()).situacao_fiscal;
    const fiscalSnapshotBefore = (await db.query('select conteudo_hash from vendas_fiscal_rascunhos where id=$1', [draftId])).rows[0].conteudo_hash;
    await assert.rejects(lifecycle.returnInvoiced({ ...cancellation, idempotencyKey: 'devolver:fluxo:fiscal' }), error => error.code === 'AV-SALES-ORDER-FISCAL');
