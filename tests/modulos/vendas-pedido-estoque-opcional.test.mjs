    const repeated = await billing.invoice({ companyId, actorId, orderId, expectedVersion: 1, idempotencyKey: 'externo:faturar', issuerSnapshot });
    assert.equal(repeated.reused, true);
    assert.equal(Number((await db.query('select count(*) n from vendas_contas_receber')).rows[0].n), 1);
    const controlled = await service.create({ context, input: { ...input, reserveStock: true, idempotencyKey: 'teste:pedido:controlado' } });
    assert.equal(controlled.ok, true, JSON.stringify(controlled.errors));
    await assert.rejects(lifecycle.confirm({ companyId, actorId, orderId: controlled.operation.id, localId, expectedVersion: controlled.operation.version, idempotencyKey: 'controlado:confirmar' }), error => error.code === 'AV-SALES-ORDER-BALANCE');
