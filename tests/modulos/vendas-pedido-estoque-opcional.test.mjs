    await db.exec(`create table fiscal_private.emissions(company_id uuid,draft_id text,origin_id text,state text);
`);
    const draftId = billed.fiscalDraftId;
    await db.query("insert into fiscal_private.emissions values($1,$2,$3,'authorized')", [companyId, draftId, controlledId]);
