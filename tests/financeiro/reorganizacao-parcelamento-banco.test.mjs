import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const empresa = '00000000-0000-4000-8000-000000000010';
const outra = '00000000-0000-4000-8000-000000000011';
const user = '00000000-0000-4000-8000-000000000001';
const centro = '00000000-0000-4000-8000-000000000020';
const migracao = readFileSync('supabase/migrations/20261020160000_reorganizar_parcelamento_id_numerico.sql', 'utf8');
test('ID bigint real: reorganiza 1850 sem UUID, preserva histórico/empresa/centro e autoriza no servidor', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role authenticated; create role anon; create schema auth;
      alter default privileges in schema public grant execute on functions to anon, authenticated;
      create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.user',true),'')::uuid$$;
      create table usuarios_empresa(empresa_id uuid,user_id uuid,status text,perfil text,dashboard_liberada boolean);
      create function usuario_area_liberada(p_empresa uuid,p_area text) returns boolean language sql as $$select exists(select 1 from usuarios_empresa where empresa_id=p_empresa and user_id=auth.uid() and status='ativo' and dashboard_liberada)$$;
      create table lancamentos(id bigint generated by default as identity primary key,empresa_id uuid,ano integer,mes text,dia integer,despesa_nome text,descricao text,valor numeric,status text,tipo_obs text,recorrencia_id uuid,centro_custo_id uuid,updated_at timestamptz);
      insert into usuarios_empresa values('${empresa}','${user}','ativo','administrador',true);
      insert into lancamentos(id,empresa_id,ano,mes,dia,despesa_nome,descricao,valor,tipo_obs,centro_custo_id) values
      (1849,'${empresa}',2026,'AGOSTO',31,'Fornecedor','Compra (1/4)',100,'parcela','${centro}'),
      (1850,'${empresa}',2026,'SETEMBRO',30,'Fornecedor','Compra (2/4)',100,'parcela','${centro}'),
      (1851,'${empresa}',2026,'OUTUBRO',31,'Fornecedor','Compra (3/4)',100,'parcela','${centro}'),
      (1852,'${empresa}',2026,'NOVEMBRO',30,'Fornecedor','Compra (4/4)',100,'parcela','${centro}'),
      (1853,'${outra}',2026,'OUTUBRO',31,'Fornecedor','Compra (3/4)',100,'parcela','${centro}'),
      (1854,'${empresa}',2026,'OUTUBRO',31,'Fornecedor','Compra (3/4)',100,'parcela',null);
      select setval(pg_get_serial_sequence('lancamentos','id'),2000);`);
    // Reproduz a falha da assinatura anterior com o mesmo identificador da captura.
    await db.exec(readFileSync('supabase/migrations/20260921090000_reorganizar_parcelamento_despesa.sql', 'utf8'));
    await assert.rejects(db.query(`select reorganizar_parcelamento_despesa_rpc('${empresa}','1850',2026,'SETEMBRO',30,'Fornecedor','Compra',100,3,5)`), /invalid input syntax for type uuid/);
    await db.exec(migracao);
    assert.equal((await db.query("select has_function_privilege('anon','public.reorganizar_parcelamento_despesa_rpc(uuid,bigint,integer,text,integer,text,text,numeric,integer,integer)','execute') as permitido")).rows[0].permitido,false);
    const chamada = `select reorganizar_parcelamento_despesa_rpc('${empresa}',1850,2026,'SETEMBRO',31,'Fornecedor','Compra',100,3,5) as resultado`;
    await assert.rejects(db.query(chamada), /sem permissão/);
    await db.query("select set_config('request.user',$1,false)",[user]);
    const antes = (await db.query('select * from lancamentos where id in (1849,1853,1854) order by id')).rows;
    const r = await db.query(chamada);
    assert.equal(r.rows[0].resultado.atualizados, 3);
    assert.deepEqual((await db.query('select * from lancamentos where id in (1849,1853,1854) order by id')).rows, antes);
    assert.deepEqual((await db.query('select id,mes,dia,descricao,valor from lancamentos where id in (1850,1851,1852) order by id')).rows, [
      {id:1850,mes:'SETEMBRO',dia:30,descricao:'Compra (3/5)',valor:'100'},
      {id:1851,mes:'OUTUBRO',dia:31,descricao:'Compra (4/5)',valor:'100'},
      {id:1852,mes:'NOVEMBRO',dia:30,descricao:'Compra (5/5)',valor:'100'},
    ]);
    const expandir = `select reorganizar_parcelamento_despesa_rpc('${empresa}',1850,2026,'SETEMBRO',31,'Fornecedor','Compra',100,3,6)`;
    await db.query(expandir);
    assert.equal((await db.query(`select count(*)::int as n from lancamentos where id>2000 and centro_custo_id='${centro}'`)).rows[0].n, 1);
    await db.query(`select reorganizar_parcelamento_despesa_rpc('${empresa}',1850,2026,'SETEMBRO',31,'Fornecedor','Compra',100,3,3)`);
    assert.equal((await db.query('select count(*)::int as n from lancamentos where id in (1851,1852) or id>2000')).rows[0].n, 0);
    await db.exec('update usuarios_empresa set dashboard_liberada=false');
    await assert.rejects(db.query(chamada), /sem permissão/);
    await db.exec('update usuarios_empresa set dashboard_liberada=true');
    await assert.rejects(db.query(`select reorganizar_parcelamento_despesa_rpc('${outra}',1853,2026,'SETEMBRO',31,'Fornecedor','Compra',100,3,5)`), /sem permissão/);
    const snapshot = (await db.query('select * from lancamentos order by id')).rows;
    await assert.rejects(db.query(`select reorganizar_parcelamento_despesa_rpc('${empresa}',1850,2026,'SETEMBRO',31,'Fornecedor','Compra',100,null,5)`), /inválidos/);
    assert.deepEqual((await db.query('select * from lancamentos order by id')).rows, snapshot);
    await db.exec("alter table lancamentos add constraint falha_futura_teste check(mes<>'DEZEMBRO')");
    await assert.rejects(db.query(expandir), /falha_futura_teste/);
    // Falha na última parcela desfaz updates/inserts anteriores da mesma chamada.
    assert.deepEqual((await db.query('select * from lancamentos order by id')).rows, snapshot);
    assert.equal((await db.query("select count(*)::int as n from pg_proc where proname='reorganizar_parcelamento_despesa_rpc'")).rows[0].n,1);
  } finally { await db.close(); }
});
