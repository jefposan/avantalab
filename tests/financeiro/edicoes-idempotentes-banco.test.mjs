import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const user='00000000-0000-4000-8000-000000000001',empresa='00000000-0000-4000-8000-000000000010',receita='00000000-0000-4000-8000-000000000020';
test('edição atômica: reenvio não duplica receita/parcelas, conflito não sobrescreve e autorização permanece obrigatória',async()=>{
  const db=new PGlite();
  try{
    await db.exec(`create role authenticated;create role anon;create role service_role;create schema auth;
      create table auth.users(id uuid primary key);create table empresas(id uuid primary key);
      insert into auth.users values('${user}');insert into empresas values('${empresa}');
      create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.user',true),'')::uuid$$;
      create table usuarios_empresa(empresa_id uuid,user_id uuid,status text,perfil text,dashboard_liberada boolean,sessao_ativa boolean);
      insert into usuarios_empresa values('${empresa}','${user}','ativo','administrador',true,true);
      create function usuario_area_liberada(p_empresa uuid,p_area text) returns boolean language sql as $$select exists(select 1 from usuarios_empresa where empresa_id=p_empresa and user_id=auth.uid() and status='ativo' and dashboard_liberada)$$;
      create function avantalab_sessao_perfil_permitida(p_empresa uuid) returns boolean language sql as $$select exists(select 1 from usuarios_empresa where empresa_id=p_empresa and user_id=auth.uid() and sessao_ativa)$$;
      create table lancamentos(id bigint generated by default as identity primary key,empresa_id uuid,ano int,mes text,dia int,despesa_nome text,descricao text,valor numeric,status text,tipo_obs text,recorrencia_id uuid,centro_custo_id uuid,updated_at timestamptz,revisao int default 1);
      create table faturamentos_entradas(id uuid primary key,empresa_id uuid,ano int,mes text,dia int,origem text,valor numeric,status text,tipo_obs text,centro_custo_id uuid,updated_at timestamptz,revisao int default 1);
      create table faturamentos(empresa_id uuid,ano int,mes text,valor numeric,unique(empresa_id,ano,mes));
      create function avancar_revisao() returns trigger language plpgsql as $$begin new.revisao=old.revisao+1;return new;end;$$;
      create trigger revisao_d before update on lancamentos for each row execute function avancar_revisao();
      create trigger revisao_r before update on faturamentos_entradas for each row execute function avancar_revisao();
      insert into lancamentos(id,empresa_id,ano,mes,dia,despesa_nome,descricao,valor,tipo_obs) values
      (1850,'${empresa}',2026,'OUTUBRO',20,'Fornecedor','Compra (1/2)',100,'parcela'),
      (1851,'${empresa}',2026,'NOVEMBRO',20,'Fornecedor','Compra (2/2)',100,'parcela');
      select setval(pg_get_serial_sequence('lancamentos','id'),2000);
      insert into faturamentos_entradas values('${receita}','${empresa}',2026,'OUTUBRO',20,'Venda',100,'confirmada',null,null,now(),1);
      insert into faturamentos values('${empresa}',2026,'OUTUBRO',300);`);
    await db.exec(readFileSync('supabase/migrations/20261020160000_reorganizar_parcelamento_id_numerico.sql','utf8'));
    const antes=(await db.query('select * from lancamentos order by id')).rows;
    await db.exec(readFileSync('supabase/migrations/20261020190000_edicoes_financeiras_idempotentes.sql','utf8'));
    assert.deepEqual((await db.query('select * from lancamentos order by id')).rows,antes);
    const args={ano:2026,mes:'OUTUBRO',dia:21,valor:125,origem:'Nova venda',status:'confirmada',tipo_obs:null};
    let n=0;
    const id=()=>`10000000-0000-4000-8000-${String(++n).padStart(12,'0')}`;
    const enviar=(operacao,tipo,registro,revisao,dados,usuario=user)=>db.query('select aplicar_edicao_financeira_mobile_rpc($1,$2,$3,$4,$5,$6::jsonb,$7) as r',[operacao,empresa,tipo,String(registro),revisao,JSON.stringify(dados),usuario]);
    await assert.rejects(enviar(id(),'receita',receita,1,args),/não autorizado/);
    await db.query("select set_config('request.user',$1,false)",[user]);
    await assert.rejects(enviar(id(),'receita',receita,1,args,empresa),/não autorizado/);
    const op=id(),primeiro=await enviar(op,'receita',receita,1,args);
    assert.equal(primeiro.rows[0].r.registro.revisao,2);
    assert.deepEqual((await enviar(op,'receita',receita,1,args)).rows,primeiro.rows);
    assert.equal((await db.query('select valor from faturamentos')).rows[0].valor,'325');
    await assert.rejects(enviar(op,'receita',receita,1,{...args,valor:500}),/já utilizado/);
    await assert.rejects(enviar(id(),'receita',receita,1,{...args,valor:500}),/outro dispositivo/);
    assert.equal((await db.query('select valor from faturamentos')).rows[0].valor,'325');
    const d={ano:2026,mes:'OUTUBRO',dia:20,valor:100,despesa_nome:'Fornecedor',descricao_base:'Compra',parcela_atual:1,total_parcelas:3,status:'confirmada',tipo_obs:'parcela'};
    const opParcela=id();await enviar(opParcela,'parcelamento',1850,1,d);await enviar(opParcela,'parcelamento',1850,1,d);
    assert.equal((await db.query('select count(*)::int n from lancamentos')).rows[0].n,3);
    assert.equal((await db.query('select revisao from lancamentos where id=1850')).rows[0].revisao,2);
    for(const condicao of ['dashboard_liberada=false','sessao_ativa=false',"status='bloqueado'"]){
      await db.exec(`update usuarios_empresa set ${condicao}`);
      await assert.rejects(enviar(op,'receita',receita,1,args),/não autorizado/);
      await db.exec("update usuarios_empresa set dashboard_liberada=true,sessao_ativa=true,status='ativo'");
    }
    // Falha posterior à atualização do total deve desfazer também esse total e o recibo.
    await db.exec("alter table faturamentos_entradas add constraint sem_erro check(origem<>'ERRO')");
    const falha=id();await assert.rejects(enviar(falha,'receita',receita,2,{...args,origem:'ERRO',valor:200}),/sem_erro/);
    assert.equal((await db.query('select valor from faturamentos')).rows[0].valor,'325');
    assert.equal((await db.query('select count(*)::int n from edicoes_financeiras_mobile where operacao_id=$1',[falha])).rows[0].n,0);
    await db.exec('set role authenticated');
    await assert.rejects(db.query('select * from edicoes_financeiras_mobile'),/permission denied/);
    await db.exec('reset role');
    assert.equal((await db.query("select has_function_privilege('anon','aplicar_edicao_financeira_mobile_rpc(uuid,uuid,text,text,integer,jsonb,uuid)','execute') ok")).rows[0].ok,false);
    await assert.rejects(enviar(id(),'despesa',1850,2,{...d,mes:'FEVEREIRO',dia:31}),/date field value out of range/);
  }finally{await db.close();}
});
